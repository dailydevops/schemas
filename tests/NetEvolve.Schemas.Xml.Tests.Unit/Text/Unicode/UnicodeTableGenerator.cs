namespace NetEvolve.Schemas.Xml.Tests.Unit.Text.Unicode;

using System.Globalization;
using System.Text;

/// <summary>
/// Emits <c>UnicodeTables.generated.cs</c> from the pinned Unicode Character Database files.
/// See <c>src/NetEvolve.Schemas.Xml/Text/Unicode/README.md</c> for how to run it.
/// </summary>
internal static class UnicodeTableGenerator
{
    /// <summary>The environment variable that makes the generator test rewrite the committed file.</summary>
    internal const string RegenerateVariable = "SCHEMAS_UCD_REGENERATE";

    // Superseded block names cited by XSD 1.1 Part 2 G.4.2.3, with the ranges as cited there.
    private static readonly (string Name, int First, int Last)[] Aliases =
    [
        ("Greek", 0x0370, 0x03FF),
        ("CombiningMarksforSymbols", 0x20D0, 0x20FF),
        ("PrivateUse", 0xE000, 0xF8FF),
        ("PrivateUse", 0xF0000, 0xFFFFD),
        ("PrivateUse", 0x100000, 0x10FFFD),
    ];

    internal static string CommittedPath() =>
        Path.Combine(
            UcdData.RepositoryRoot(),
            "src",
            "NetEvolve.Schemas.Xml",
            "Text",
            "Unicode",
            "UnicodeTables.generated.cs"
        );

    internal static string Generate(UcdData ucd)
    {
        var version = ucd.Manifest.SourceUrl.Segments[^3].TrimEnd('/');
        var sb = new StringBuilder();
        _ = sb.Append("// <auto-generated>\n")
            .Append("//   Generated from the Unicode Character Database ")
            .Append(version)
            .Append(" pinned in tests/conformance/suites/ucd.json.\n")
            .Append("//   Do not edit by hand; see README.md in this folder for how to regenerate.\n")
            .Append("// </auto-generated>\n\n")
            .Append("namespace NetEvolve.Schemas.Xml.Text.Unicode;\n\n")
            .Append("internal static partial class UnicodeTables\n{");

        var (categoryStarts, categoryValues) = Runs(ucd.Categories.Length, cp => ucd.Categories[cp]);
        AppendArray("int", "CategoryStarts", categoryStarts, sb);
        AppendArray("byte", "CategoryValues", categoryValues, sb);

        var (blockStarts, blockValues) = Runs(ucd.BlockOfCodePoint.Length, cp => ucd.BlockOfCodePoint[cp]);
        AppendArray("int", "BlockStarts", blockStarts, sb);
        AppendArray("short", "BlockValues", blockValues, sb);
        AppendStrings("BlockNames", ucd.Blocks.ConvertAll(b => b.Name), sb);

        AppendNameTable(ucd, sb);

        AppendArray("int", "FoldKeys", ucd.Folds.ConvertAll(f => f.Key), sb);
        AppendArray("int", "FoldValues", ucd.Folds.ConvertAll(f => f.Value), sb);

        _ = sb.Append("}\n");
        return sb.ToString();
    }

    private static void AppendNameTable(UcdData ucd, StringBuilder sb)
    {
        // Name rows are sorted for binary search. A name with several ranges chains its extra rows, which sit behind
        // the sorted rows, through NameNext.
        var sorted = new List<(string Name, int First, int Last)>();
        foreach (var (first, last, name) in ucd.Blocks)
        {
            sorted.Add((UcdData.Normalize(name), first, last));
        }

        var extras = new List<(string Name, int First, int Last)>();
        foreach (var alias in Aliases)
        {
            if (sorted.Exists(r => string.Equals(r.Name, alias.Name, StringComparison.Ordinal)))
            {
                extras.Add(alias);
            }
            else if (extras.Exists(r => string.Equals(r.Name, alias.Name, StringComparison.Ordinal)))
            {
                extras.Add(alias);
            }
            else
            {
                sorted.Add(alias);
            }
        }

        sorted.Sort(static (a, b) => string.CompareOrdinal(a.Name, b.Name));
        for (var i = 1; i < sorted.Count; i++)
        {
            if (string.Equals(sorted[i].Name, sorted[i - 1].Name, StringComparison.Ordinal))
            {
                throw new InvalidOperationException($"Duplicate normalized block name '{sorted[i].Name}'.");
            }
        }

        var next = new List<int>();
        for (var i = 0; i < sorted.Count; i++)
        {
            next.Add(-1);
        }

        var tail = sorted.Count;
        foreach (var (extraName, _, _) in extras)
        {
            var head = sorted.FindIndex(r => string.Equals(r.Name, extraName, StringComparison.Ordinal));
            while (next[head] >= 0)
            {
                head = next[head];
            }

            next[head] = tail++;
            next.Add(-1);
        }

        AppendStrings("NameKeys", sorted.ConvertAll(r => r.Name), sb);
        var all = new List<(string Name, int First, int Last)>(sorted);
        all.AddRange(extras);
        AppendArray("int", "NameFirst", all.ConvertAll(r => r.First), sb);
        AppendArray("int", "NameLast", all.ConvertAll(r => r.Last), sb);
        AppendArray("short", "NameNext", next, sb);
    }

    private static (List<int> Starts, List<int> Values) Runs(int count, Func<int, int> valueOf)
    {
        var starts = new List<int>();
        var values = new List<int>();
        for (var cp = 0; cp < count; cp++)
        {
            var value = valueOf(cp);
            if (values.Count == 0 || values[^1] != value)
            {
                starts.Add(cp);
                values.Add(value);
            }
        }

        return (starts, values);
    }

    private static void AppendStrings(string name, List<string> values, StringBuilder sb)
    {
        _ = sb.Append("\n    private static readonly string[] ").Append(name).Append(" =\n    [\n");
        foreach (var value in values)
        {
            _ = sb.Append("        \"").Append(value).Append("\",\n");
        }

        _ = sb.Append("    ];\n");
    }

    private static void AppendArray(string type, string name, List<int> values, StringBuilder sb)
    {
        _ = sb.Append("\n    private static readonly ").Append(type).Append("[] ").Append(name).Append(" =\n    [");
        for (var i = 0; i < values.Count; i++)
        {
            _ = sb.Append(i % 16 == 0 ? "\n        " : " ");
            _ = sb.Append(
                string.Equals(type, "int", StringComparison.Ordinal)
                    ? "0x" + values[i].ToString("X", CultureInfo.InvariantCulture)
                    : values[i].ToString(CultureInfo.InvariantCulture)
            );
            _ = sb.Append(',');
        }

        _ = sb.Append("\n    ];\n");
    }
}
